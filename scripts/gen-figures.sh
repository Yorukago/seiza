#!/bin/sh
# Turns figures/*.fig into a C table of built-in figures: gen-figures.sh figures-dir > header.
echo '/* generated by scripts/gen-figures.sh from the files in figures/: do not edit */'
echo 'static const struct { const char *name, *text; } PRESETS[] = {'
for f in "$1"/*.fig; do
	printf '\t{ "%s",\n' "$(basename "$f" .fig)"
	sed 's/\\/\\\\/g; s/"/\\"/g; s/^/\t  "/; s/$/\\n"/' "$f"
	printf '\t},\n'
done
echo '};'
